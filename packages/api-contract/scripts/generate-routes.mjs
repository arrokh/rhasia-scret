async function readGenerated(path, description) {
  try {
    return await readFile(path, "utf8");
  } catch {
    throw new Error(`${description} is missing; run pnpm run generate:routes`);
  }
}

if (process.argv.includes("--check")) {
  const [currentTypescript, currentGo] = await Promise.all([
    readGenerated(outputPath, "Generated TypeScript route manifest"),
    readGenerated(goOutputPath, "Generated Go API dispatcher"),
  ]);
  if (currentTypescript !== generated)
    throw new Error("Generated TypeScript route manifest is stale; run pnpm run generate:routes");
  if (currentGo !== generatedGo) throw new Error("Generated Go API dispatcher is stale; run pnpm run generate:routes");
  console.log(`OpenAPI route artifacts are current (${manifest.length} operations)`);
} else {
  await Promise.all([writeFile(outputPath, generated), writeFile(goOutputPath, generatedGo)]);
  console.log(`Generated TypeScript and Go route artifacts (${manifest.length} operations)`);
}
